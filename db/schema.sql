-- FinPulse schema: Lion City Supplies Pte Ltd (made-up data, all amounts in SGD).
-- Money is NUMERIC(14,2), dates are DATE. Re-running this file resets the data.

DROP TABLE IF EXISTS actions CASCADE;
DROP TABLE IF EXISTS bill_lines CASCADE;
DROP TABLE IF EXISTS bills CASCADE;
DROP TABLE IF EXISTS receipt_lines CASCADE;
DROP TABLE IF EXISTS goods_receipts CASCADE;
DROP TABLE IF EXISTS po_lines CASCADE;
DROP TABLE IF EXISTS purchase_orders CASCADE;
DROP TABLE IF EXISTS suppliers CASCADE;
DROP TABLE IF EXISTS credit_notes CASCADE;
DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS invoices CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

-- Money coming in ---------------------------------------------------------

CREATE TABLE customers (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL UNIQUE,
    email               TEXT NOT NULL CHECK (email LIKE '%@example.com'),
    payment_terms_days  INTEGER NOT NULL CHECK (payment_terms_days > 0)
);

CREATE TABLE invoices (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no   TEXT NOT NULL UNIQUE,
    customer_id  INTEGER NOT NULL REFERENCES customers (id),
    issue_date   DATE NOT NULL,
    due_date     DATE NOT NULL,
    amount       NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    status       TEXT NOT NULL CHECK (status IN ('open', 'partially_paid', 'paid')),
    CHECK (due_date >= issue_date)
);
CREATE INDEX invoices_customer_idx ON invoices (customer_id);

CREATE TABLE payments (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  INTEGER NOT NULL REFERENCES invoices (id),
    paid_on     DATE NOT NULL,
    amount      NUMERIC(14,2) NOT NULL CHECK (amount > 0)
);
CREATE INDEX payments_invoice_idx ON payments (invoice_id);

CREATE TABLE credit_notes (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  INTEGER NOT NULL REFERENCES invoices (id),
    amount      NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    reason      TEXT NOT NULL,
    issued_on   DATE NOT NULL
);
CREATE INDEX credit_notes_invoice_idx ON credit_notes (invoice_id);

-- Money going out ---------------------------------------------------------

CREATE TABLE suppliers (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL UNIQUE,
    email               TEXT NOT NULL CHECK (email LIKE '%@example.com'),
    payment_terms_days  INTEGER NOT NULL CHECK (payment_terms_days > 0)
);

CREATE TABLE purchase_orders (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_no        TEXT NOT NULL UNIQUE,
    supplier_id  INTEGER NOT NULL REFERENCES suppliers (id),
    ordered_on   DATE NOT NULL,
    total        NUMERIC(14,2) NOT NULL CHECK (total > 0)
);
CREATE INDEX purchase_orders_supplier_idx ON purchase_orders (supplier_id);

CREATE TABLE po_lines (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id       INTEGER NOT NULL REFERENCES purchase_orders (id),
    item        TEXT NOT NULL,
    qty         INTEGER NOT NULL CHECK (qty > 0),
    unit_price  NUMERIC(14,2) NOT NULL CHECK (unit_price > 0)
);
CREATE INDEX po_lines_po_idx ON po_lines (po_id);

CREATE TABLE goods_receipts (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id        INTEGER NOT NULL REFERENCES purchase_orders (id),
    received_on  DATE NOT NULL
);
CREATE INDEX goods_receipts_po_idx ON goods_receipts (po_id);

CREATE TABLE receipt_lines (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id    INTEGER NOT NULL REFERENCES goods_receipts (id),
    item          TEXT NOT NULL,
    qty_received  INTEGER NOT NULL CHECK (qty_received >= 0)
);
CREATE INDEX receipt_lines_receipt_idx ON receipt_lines (receipt_id);

CREATE TABLE bills (
    id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_no                    TEXT NOT NULL UNIQUE,
    supplier_id                INTEGER NOT NULL REFERENCES suppliers (id),
    po_id                      INTEGER REFERENCES purchase_orders (id),
    bill_date                  DATE NOT NULL,
    due_date                   DATE NOT NULL,
    amount                     NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    status                     TEXT NOT NULL
        CHECK (status IN ('pending_approval', 'approved', 'paid', 'rejected')),
    submitted_for_approval_on  DATE NOT NULL,
    CHECK (due_date >= bill_date)
);
CREATE INDEX bills_supplier_idx ON bills (supplier_id);
CREATE INDEX bills_po_idx ON bills (po_id);

CREATE TABLE bill_lines (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id     INTEGER NOT NULL REFERENCES bills (id),
    item        TEXT NOT NULL,
    qty         INTEGER NOT NULL CHECK (qty > 0),
    unit_price  NUMERIC(14,2) NOT NULL CHECK (unit_price > 0)
);
CREATE INDEX bill_lines_bill_idx ON bill_lines (bill_id);

-- Agent actions (written only by the month-end check and the CLI) ---------
-- target_type + target_id point at an invoice, bill or customer, so there is
-- no foreign key. created_at has no default on purpose: dates come from AS_OF.

CREATE TABLE actions (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type  TEXT NOT NULL,
    target_type  TEXT NOT NULL CHECK (target_type IN ('invoice', 'bill', 'customer')),
    target_id    INTEGER NOT NULL,
    draft_text   TEXT NOT NULL,
    status       TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at   TIMESTAMPTZ NOT NULL,
    decided_at   TIMESTAMPTZ,
    decided_by   TEXT
);
